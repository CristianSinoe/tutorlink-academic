package com.sinoe.authmfa.demo;

import org.junit.jupiter.api.Test;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import static org.assertj.core.api.Assertions.*;

class DemoSnapshotTest {
    private Connection database(String name) throws SQLException {
        return DriverManager.getConnection("jdbc:h2:mem:" + name + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE", "sa", "");
    }
    private void schema(Connection c) throws SQLException {
        try (var s = c.createStatement()) {
            s.execute("create table parent(id bigint generated by default as identity primary key, name varchar(100), child_id bigint)");
            s.execute("create table child(id bigint generated by default as identity primary key, parent_id bigint references parent(id))");
            s.execute("alter table parent add foreign key(child_id) references child(id)");
        }
    }
    @Test
    void copiesCyclesPreservesIdsReseedsIdentityAndDisappearsAfterClose() throws Exception {
        String name = UUID.randomUUID().toString();
        try (var source = database(UUID.randomUUID().toString())) {
            schema(source);
            try (var s = source.createStatement()) {
                s.execute("insert into parent(id,name) values (40,'Original á')");
                s.execute("insert into child(id,parent_id) values (80,40)");
                s.execute("update parent set child_id=80 where id=40");
            }
            try (var target = database(name)) {
                schema(target);
                assertThat(DemoSnapshot.copy(source, target)).isEqualTo(2);
                try (var s = target.createStatement()) {
                    s.execute("insert into parent(name) values ('Synthetic')");
                    try (var r = s.executeQuery("select max(id) from parent")) {
                        r.next(); assertThat(r.getLong(1)).isEqualTo(41);
                    }
                    assertThatThrownBy(() -> s.execute("insert into child(parent_id) values (999)"))
                            .isInstanceOf(SQLException.class);
                    s.execute("update parent set name='Changed' where id=40");
                }
            }
            try (var s = source.createStatement(); var r = s.executeQuery("select name from parent")) {
                r.next(); assertThat(r.getString(1)).isEqualTo("Original á");
                assertThat(r.next()).isFalse();
            }
            try (var reopened = database(name); var s = reopened.createStatement()) {
                assertThatThrownBy(() -> s.executeQuery("select * from parent")).isInstanceOf(SQLException.class);
            }
        }
    }
    @Test
    void refusesIncompleteSourceInsteadOfSilentlySkippingIt() throws Exception {
        try (var source = database(UUID.randomUUID().toString()); var target = database(UUID.randomUUID().toString())) {
            schema(target);
            assertThatThrownBy(() -> DemoSnapshot.copy(source, target)).isInstanceOf(SQLException.class);
        }
    }
}
